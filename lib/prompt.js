/** 第九通路 — 提示词与说明书文本。所有产物都是 UTF-8 with BOM 的 TXT。 */

export const TOOL_NAME = '第九通路';
export const AUTHOR = '无银ui';
export const EMAIL = 'a1lzui@163.com';
export const VERSION = '0.1.3';

export const PROMPT_FILE = '恢复说明.txt';
export const MANUAL_FILE = '使用说明书.txt';
export const SHORT_PHRASE = '扫描所有盘符，找到名为「第九通路备份」的文件夹里的 manifest.json，按恢复说明.txt 恢复我的全部对话。';

function header(title) {
  return `${title}\n${'='.repeat(36)}\n`;
}

/** 恢复用提示词：用户把这个文件的内容整段粘贴到新客户端对话框即可。 */
export function buildPrompt({ kitName, hostVersion, sessionFormat, workspaces, createdAt }) {
  const lines = [
    header(`${TOOL_NAME} · 恢复提示词`),
    '把这整段内容粘贴到新客户端的对话框里，或让 agent 直接读取本文件。',
    '',
    `备份目录名：${kitName}`,
    `备份时间：${createdAt}`,
    `备份时的客户端版本：${hostVersion}（会话格式 ${sessionFormat}）`,
    `备份包含的工作区：${workspaces.length} 个`,
    ...workspaces.map((w) => `  - ${w.path}`),
    '',
    header('一、你要做的事'),
    '1. 先装好同版本客户端，并启动一次；确认能打开一个空白对话。',
    '2. 安装本插件（新客户端默认没有它，必须先装）。本目录下的 plugin/ 就是插件包，三种方式：',
    '   首选：让 agent 用 plugin_manager 的 install_bundle，target 指向这个 plugin 目录。',
    '   次选：在 设置 → 插件 里从本地目录/路径安装（界面若有该入口）。',
    '   备选：先装好 dsh 命令行，再执行  dsh plugin --profile <profile 名> add "<本目录>\\plugin"',
    '   注意：桌面版通常没有 dsh 命令，命令行方式不一定可用。',
    '   装完重启一次客户端，插件提供的工具才会出现。',
    '3. 新建一个工作区，随便叫什么名字，用来执行恢复。这个工作区不会被恢复内容覆盖。',
    `4. 在这个工作区里发起对话，粘贴本文件全文，或直接说：「${SHORT_PHRASE}」`,
    '',
    header('二、agent 必须遵守的顺序'),
    '1. 读取本目录的 manifest.json，核对 createdBy.dshVersion 与当前客户端版本。',
    '   次版本或主版本不同就停下来告诉用户，不要继续。',
    '2. 逐项确认恢复内容：宿主数据（会话、工作区注册）、工作区文件、附件。',
    '   只有 manifest.layers 里对应层有内容时，这一项才可选。',
    '3. 对每个工作区判断恢复方式，不要一律提问：',
    '   - 旧路径在新系统上仍然存在且可写 → 直接用，不问用户。',
    '   - 旧路径已失效 → 提问：指定一个新路径，或直接用备份里该工作区的副本。',
    '   - 用户暂时不想恢复 → 跳过，并在报告里写明。',
    '4. 询问是否恢复 AGENTS.md（全局偏好文件）。三个选项：跳过 / 覆盖 / 并存。',
    '   默认跳过，因为它会改变所有后续会话的行为。',
    '5. 执行前先给现有数据拍一份快照，再合并写入，不要整体替换目录。',
    '   正在运行的这个会话必须跳过，否则它会覆盖自己。',
    '6. 恢复完成后生成 Word 报告，然后提示用户重启客户端。',
    '',
    header('三、不要做的事'),
    '- 不要改写会话正文里出现的旧绝对路径，那是内容不是索引。',
    '- 不要恢复工作区以外的文件、已删除的内容、插件私有数据和任何外部副作用。',
    '- 不要因为路径不同就判定恢复失败；记录差异，交给用户判断。',
    '- 不要跳过重启这一步，会话列表是启动时读取的。',
    '',
    header('四、恢复后的预期'),
    `- 会话会出现在对应工作区下，可以正常打开、继续对话。`,
    '- 若某个工作区只恢复了注册、没有恢复文件，打开会话时目录可能是空的。',
    '- 客户端被自动更新到更新的版本时，版本号前移属于正常现象，不影响已恢复数据。',
    '',
    '—',
    `${TOOL_NAME} v${VERSION} · 作者 ${AUTHOR} · ${EMAIL}`,
    '本文档由 AI 参与生成。',
    '',
  ];
  return lines.join('\n');
}

/** 使用说明书：装在哪里、怎么备份、怎么恢复、边界是什么。 */
export function buildManual() {
  return [
    header(`${TOOL_NAME} 使用说明书`),
    `作者：${AUTHOR}   邮箱：${EMAIL}   版本：${VERSION}`,
    '',
    '本文件由 AI 参与生成。',
    '',
    header('一、这个工具做什么'),
    `${TOOL_NAME} 把客户端的数据备份到非系统盘，并在新机器上用一段提示词恢复。`,
    '它解决的具体场景是：重装系统只格式化 C 盘，其它盘的数据还在，',
    '但客户端和它的数据目录（默认在 C 盘用户目录下）已经没了。',
    '',
    '备份的内容分三层，可以分别选择：',
    '  1. 宿主数据：会话记录、工作区注册表、全局偏好、技能。',
    '  2. 工作区文件：工作区目录里的项目文件（可选，按工作区勾选）。',
    '  3. 附件：会话里的图片等二进制资源（可选）。',
    '',
    header('二、备份前要满足的条件'),
    '- 备份目标必须在非系统盘。工具会自己判断系统卷，不允许写到 C 盘。',
    '- 目标盘在备份完成后至少保留 5 GB 剩余空间。',
    '- 不要在另一个备份正在进行时再发起一次。',
    '',
    header('三、备份步骤'),
    '1. 在对话里说「备份到 E 盘」或「备份全部数据到 E:\\备份」。',
    '2. 工具会问你要备份哪几层、哪些工作区。',
    '3. 完成后备份目录里会有 manifest.json、恢复说明.txt、本说明书、插件包和哈希清单。',
    '',
    header('四、恢复步骤'),
    '1. 装好同版本客户端，启动一次。',
    '2. 安装插件（插件包在备份目录的 plugin/ 下，可离线安装），按可用程度选一种：',
    '   - 首选：让 agent 用 plugin_manager 的 install_bundle，target 指向 plugin/ 目录。',
    '   - 次选：设置 → 插件 页面里从本地目录安装。',
    '   - 备选：已装 dsh 命令行时，执行 dsh plugin --profile <profile> add "<备份目录>\\plugin"。',
    '   桌面版通常没有 dsh 命令，不要假定它存在。装完必须重启客户端。',
    '3. 新建一个工作区（恢复工作区），在这里发起对话。',
    '4. 粘贴「恢复说明.txt」的内容，或让 agent 读这个文件。',
    '5. 按 agent 的提问选择每个工作区的去向。',
    '6. 恢复完成后重启客户端。',
    '',
    header('五、能恢复什么、不能恢复什么'),
    '能：宿主数据、工作区注册与路径、会话全文、工作区目录内的文件（若勾选）。',
    '不能：工作区以外的文件、已删除的内容、插件自己的私有数据、',
    '      以及一切外部副作用（推送、安装、网络请求）。',
    '',
    header('六、几个必须知道的限制'),
    '- 执行备份的那条会话不会被备份，它是工具会话。',
    '- 未登记在任何工作区名下的会话不会进备份，预检里会单独报出数量。',
    '- 恢复时正在运行的那条会话会被跳过，避免覆盖自己。',
    '- 会话正文里的旧绝对路径不会改写，属于历史记录。',
    '- 恢复后必须重启客户端，会话列表才会刷新。',
    '- 客户端装的是备份时的版本；若随后被自动更新，版本号前移是正常的。',
    '',
    header('七、文件说明'),
    '  manifest.json        备份清单，所有工具都读它',
    '  恢复说明.txt          给新客户端 agent 的提示词',
    '  使用说明书.txt        就是本文件',
    '  SHA256SUMS.txt       逐文件校验值',
    '  host/                宿主数据',
    '  workspaces/          工作区文件副本（若勾选）',
    '  attachments/         附件（若勾选）',
    '  plugin/              本插件安装包',
    '  installer/           同版本客户端安装包（若找到）',
    '',
    '—',
    `${TOOL_NAME} v${VERSION} · ${AUTHOR} · ${EMAIL}`,
    '',
  ].join('\n');
}

export function withBom(text) {
  return `\ufeff${text}`;
}
